app_env <- function() {
  skip_if_not_installed("shiny")
  skip_if_not_installed("bslib")
  withr::local_options(shiny.maxRequestSize = getOption("shiny.maxRequestSize"), .local_envir = parent.frame())
  env <- new.env(parent = globalenv())
  sys.source(system.file("app", "app.R", package = "heterogeneity"), envir = env)
  env
}

test_that("an upload runs step by step, keeps missing values and clears stale results", {
  app <- app_env()
  set.seed(42)
  d <- data.frame(y = rnorm(240), arm = rep(c("control", "treated"), 120), age = rnorm(240),
                  region = rep(c("North", "South", "East"), 80), school = rep(letters[1:20], 12),
                  weight = rep(c(1, 2), 120))
  d$age[1:40] <- NA
  path <- tempfile(fileext = ".csv"); on.exit(unlink(path), add = TRUE)
  utils::write.csv(d, path, row.names = FALSE)
  shiny::testServer(app$server, {
    session$setInputs(file = list(datapath = path, name = "upload.csv"))
    expect_equal(rv$source, "upload")
    # Every field of step 1 is shown at once, ending with the button to step 2.
    fields <- output$fields$html
    for (label in c("Dependent variable (Y)", "Independent variable (W)", "Characteristics (X)", "Optional settings",
                    "Continue to step 2: Run the forest")) expect_match(fields, label, fixed = TRUE)
    session$setInputs(run = 1)
    expect_null(rv$res)
    expect_match(rv$run_note, "Choose a dependent variable (Y), an independent variable (W) and at least one characteristic (X) first.", fixed = TRUE)
    session$setInputs(y = "y", w = "arm", treated = "treated", x = c("age", "region"),
                      ids = "", weights = "weight", clusters = "school", num_trees = 100, seed = 21042020)
    expect_true(w_needs_coding())
    session$setInputs(run = 2)
    expect_null(rv$error)
    expect_null(rv$run_note)
    r <- rv$res$report
    expect_s3_class(r, "heterogeneity_report")
    expect_equal(sum(is.na(r$X$age)), 40L)
    expect_true(r$settings$weighted)
    expect_equal(r$settings$w_labels, c(`0` = "control", `1` = "treated"))
    expect_equal(rv$unit, 1)
    expect_match(output$next_ui$html, "Continue to step 3: Compare groups")
    # Step 2 holds the summary and all three plots at once.
    summary_html <- paste(as.character(unit_ui("run")))
    for (id in c("unit-summary", "unit-spread", "unit-characteristics", "unit-profiles")) expect_match(summary_html, id)
    session$setInputs(next_step = 1)
    expect_match(output$next_ui$html, "Continue to step 4: Export results")
    session$setInputs(next_step = 2)
    expect_equal(rv$unit, length(app$units))
    expect_match(paste(as.character(unit_ui("groups"))), "selected>", fixed = TRUE)
    expect_false(grepl("dl_groups|dl_importance", paste(as.character(unit_ui("groups")), as.character(unit_ui("export")))))
    expect_match(summary_html, "used for the forest and all averages")
    expect_match(summary_html, "candidate moderators")
    expect_match(summary_html, "run from")
    # The key sentence gives the average treatment effect in Y's units and in standard deviations; there is no summary table.
    expect_match(summary_html, sprintf('average treatment effect<span class="tip" role="tooltip">'), fixed = TRUE)
    expect_match(summary_html, sprintf('</span></span> is <b>%s</b> (<b>%s</b> <span class="term" tabindex="0">standard deviations',
                                       app$fmt(r$ate$estimate), app$fmt(r$ate$standardized)), fixed = TRUE)
    expect_match(summary_html, 'conditional on its covariates (called a <a href="https://bookdown.org/stanfordgsbsilab/ml-ci-tutorial/hte-i-binary-treatment.html"', fixed = TRUE)
    expect_false(grepl("Table of groups|effect_table|Copy text", paste(as.character(unit_ui("groups")), as.character(unit_ui("export")))))
    expect_false(grepl("<table|Quantity|Central 90|Mean prediction by group", summary_html))
    expect_match(paste(as.character(report_text(facts()))), "Average treatment effect: </b>", fixed = TRUE)
    expect_match(paste(as.character(report_text(facts()))), "standard deviations).", fixed = TRUE)
    expect_match(profile_text()$short, "bottom 20% and the top 20% of estimated treatment effects differ most on", fixed = TRUE)
    expect_match(spread_text(facts())$long, "teal bars, above 0, mark effects where")
    expect_match(spread_text(facts())$short, "around the average treatment effect of")
    for (plot in c("dist", "importance", "profiles")) expect_type(output[[plot]], "list")
    # Dark mode recolours a copy of each plot; the cached plot keeps its colours.
    session$setInputs(mode = "dark")
    dark_bars <- for_page(importance_plot())
    expect_identical(dark_bars$layers[[1]]$aes_params$fill, "#72a9ac")
    expect_identical(importance_plot()$layers[[1]]$aes_params$fill, "#286b70")
    expect_type(output$importance, "list")
    session$setInputs(mode = "light")
    expect_identical(for_page(importance_plot())$layers[[1]]$aes_params$fill, "#286b70")
    expect_equal(importance_height(), 260)
    session$setInputs(x1 = "region", x2 = "")
    expect_equal(sum(effect_tab()$n), nrow(d))
    expect_match(output$effect_text$html, "smallest for")
    session$setInputs(x2 = "age")
    expect_length(attr(effect_tab(), "plot")$levels, 2L)
    expect_match(output$effect_text$html, "leaves out missing values")
    summary_text <- paste(as.character(report_text(facts())))
    expect_match(summary_text, "Averages use the supplied weights")
    expect_false(grepl("Data: |Without weights|kept for the forest", summary_text))
    expect_match(summary_text, "part of this spread could be estimation noise")
    expect_false(grepl("p-value|confidence|Holm|AUTOC", summary_text))
    session$setInputs(seed = 2)
    expect_null(rv$res)
    expect_equal(rv$unit, 0)
    session$setInputs(run = 3)
    expect_s3_class(rv$res$report, "heterogeneity_report")
    session$setInputs(weights = "")
    expect_null(rv$res)
    session$setInputs(num_trees = 1)
    session$setInputs(run = 4)
    expect_null(rv$res)
    expect_match(rv$error, "whole number")
  })
})

test_that("the GSS example link downloads the data and fills in readable labels", {
  skip_on_cran()
  skip_if_not_installed("gssr")
  skip_if_offline("gss.norc.org")
  app <- app_env()
  shiny::testServer(app$server, {
    session$setInputs(example = 1)
    expect_true(example())
    expect_identical(data(), load_gss2024()$data)
    session$setInputs(y = "rating_trump", w = "conservative", x = c("lkelyvot", "age", "income16"),
                      ids = "id", weights = "", clusters = "", num_trees = 100, seed = 21042020)
    expect_false(w_needs_coding())
    session$setInputs(run = 1)
    r <- rv$res$report
    expect_identical(r$settings$effect_label, load_gss2024()$effect_label)
    expect_identical(r$labels[["lkelyvot"]], "Likelihood of voting")
    expect_identical(r$cates$id, load_gss2024()$data$id)
    expect_match(paste(as.character(unit_ui("run"))), "higher for Conservative than for Liberal/moderate")
  })
})

