test_that("a numeric comparison runs as slopes in the app", {
  app <- app_env()
  set.seed(5)
  d <- data.frame(score = rnorm(200), hours = runif(200, 0, 10), age = rnorm(200))
  d$score <- d$score + d$hours * (0.2 + 0.3 * (d$age > 0))
  path <- tempfile(fileext = ".csv"); on.exit(unlink(path), add = TRUE)
  utils::write.csv(d, path, row.names = FALSE)
  shiny::testServer(app$server, {
    session$setInputs(file = list(datapath = path, name = "dose.csv"))
    session$setInputs(y = "score", w = "hours", x = "age", ids = "", weights = "", clusters = "", num_trees = 100, seed = 21042020)
    expect_false(w_needs_coding())
    session$setInputs(run = 1)
    expect_null(rv$error)
    expect_identical(rv$res$report$settings$w_type, "continuous")
    expect_match(paste(as.character(unit_ui("run"))), "per one-unit increase in")
    expect_match(spread_text(facts())$long, "rises with")
    for (k in seq_len(length(app$units) - 1)) session$setInputs(next_step = k)
    session$setInputs(x1 = "age", x2 = "")
    expect_false(any(grepl("n_control|n treated", names(effect_tab()))))
    expect_match(paste(as.character(report_text(facts()))), "per one-unit increase in hours")
  })
})

test_that("uploads with odd delimiters, encodings, headers, blanks and labels are read", {
  app <- app_env()
  dir <- withr::local_tempdir()
  base <- data.frame(score = c(1.5, 2, 3.25, 4), group = c("a", "b", "a", "b"), city = c("K\u00f6ln", "Paris", "Z\u00fcrich", "Oslo"))
  semi <- file.path(dir, "semi.csv"); utils::write.table(base, semi, sep = ";", row.names = FALSE, quote = FALSE)
  out <- app$read_upload(semi, "semi.csv")
  expect_identical(names(out$data), names(base))
  expect_equal(out$data$score, base$score)
  tsv <- file.path(dir, "tabs.tsv"); utils::write.table(base, tsv, sep = "\t", row.names = FALSE)
  expect_equal(app$read_upload(tsv, "tabs.tsv")$data$city, base$city)
  latin <- file.path(dir, "latin.csv"); utils::write.csv(base, latin, row.names = FALSE, fileEncoding = "latin1")
  latin_out <- app$read_upload(latin, "latin.csv")
  expect_equal(latin_out$data$city, base$city)
  expect_match(paste(latin_out$notes, collapse = " "), "Latin-1")
  bare <- file.path(dir, "bare.csv"); writeLines(c("1,2,3", "4,5,6", "7,8,9"), bare)
  bare_out <- app$read_upload(bare, "bare.csv")
  expect_identical(names(bare_out$data), c("column1", "column2", "column3"))
  expect_equal(nrow(bare_out$data), 3L)
  messy <- file.path(dir, "messy.csv")
  writeLines(c("id,,score,empty", "1,x,2.5,", ",,,", "2,y,N/A,", "3,z,3.5,"), messy)
  messy_out <- app$read_upload(messy, "messy.csv")
  expect_identical(names(messy_out$data), c("id", "column2", "score"))
  expect_equal(nrow(messy_out$data), 3L)
  expect_true(is.na(messy_out$data$score[2]))
  expect_match(paste(messy_out$notes, collapse = " "), "empty column")
  empty <- file.path(dir, "empty.csv"); file.create(empty)
  expect_error(app$read_upload(empty, "empty.csv"), "empty")
  expect_error(app$read_upload(semi, "data.json"), "please upload")
  skip_if_not_installed("haven")
  lab <- data.frame(y = rnorm(120), w = rep(1:2, 60), age = rnorm(120))
  lab$w <- haven::labelled(lab$w, labels = c(Control = 1, Treated = 2), label = "Study arm")
  attr(lab$y, "label") <- "Wellbeing score"
  sav <- file.path(dir, "labelled.sav"); haven::write_sav(lab, sav)
  sav_out <- app$read_upload(sav, "labelled.sav")
  expect_identical(unname(sav_out$labels[c("y", "w")]), c("Wellbeing score", "Study arm"))
  expect_identical(sav_out$value_labels$w, c(`1` = "Control", `2` = "Treated"))
  expect_true(is.numeric(sav_out$data$w) && is.null(attributes(sav_out$data$w)))
  shiny::testServer(app$server, {
    session$setInputs(file = list(datapath = sav, name = "labelled.sav"))
    session$setInputs(y = "y", w = "w", treated = "2", x = "age", ids = "", weights = "", clusters = "", num_trees = 100, seed = 1)
    session$setInputs(run = 1)
    expect_equal(rv$res$report$settings$w_labels, c(`0` = "Control", `1` = "Treated"))
    expect_identical(rv$res$report$settings$effect_label, "Treatment effect on Wellbeing score")
  })
})

test_that("Y is chosen like W: two text values get a choice of the value coded 1", {
  app <- app_env()
  set.seed(15)
  d <- data.frame(voted = sample(c("yes", "no"), 300, TRUE), arm = rep(c("control", "treated"), 150), age = rnorm(300))
  path <- tempfile(fileext = ".csv"); on.exit(unlink(path), add = TRUE)
  utils::write.csv(d, path, row.names = FALSE)
  shiny::testServer(app$server, {
    session$setInputs(file = list(datapath = path, name = "votes.csv"))
    expect_match(output$fields$html, "Dependent variable (Y)", fixed = TRUE)
    expect_true("voted" %in% y_pool(NULL))
    session$setInputs(y = "voted", w = "arm")
    expect_true(y_needs_coding())
    expect_match(output$pick_y_one$html, "Value of voted coded 1", fixed = TRUE)
    session$setInputs(y_one = "yes", treated = "treated", x = "age", ids = "", weights = "", clusters = "", num_trees = 100, seed = 1)
    session$setInputs(run = 1)
    expect_null(rv$error)
    r <- rv$res$report
    expect_identical(unname(r$settings$y_labels), c("no", "yes"))
    expect_identical(r$settings$effect_label, "Treatment effect on the share with voted = yes")
    expect_match(paste(as.character(unit_ui("run"))), "the share with <code>voted</code> = yes is on average", fixed = TRUE)
    expect_match(paste(as.character(unit_ui("run"))), "percentage points")
  })
})

